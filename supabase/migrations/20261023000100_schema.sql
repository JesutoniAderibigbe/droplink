-- (select auth.uid()) instead of auth.uid() lets Postgres evaluate it once per
-- statement rather than once per row.
create policy "profiles: read own" on public.profiles
  for select to authenticated using (id = (select auth.uid()));
create policy "profiles: update own" on public.profiles
  for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "devices: read own" on public.devices
  for select to authenticated using (user_id = (select auth.uid()));
create policy "devices: register own" on public.devices
  for insert to authenticated with check (user_id = (select auth.uid()) and revoked_at is null);
create policy "devices: update own" on public.devices
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- Helper: does the current user own this (non-revoked) device?
create function private.owns_device(p_device_id uuid, p_allow_revoked boolean default false)
returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.devices d
    where d.id = p_device_id
      and d.user_id = (select auth.uid())
      and (p_allow_revoked or d.revoked_at is null)
  )
$$;
grant usage on schema private to authenticated;

create policy "push: read own" on public.push_subscriptions
  for select to authenticated using (private.owns_device(device_id, true));
create policy "push: add for own active device" on public.push_subscriptions
  for insert to authenticated with check (private.owns_device(device_id));
create policy "push: delete own" on public.push_subscriptions
  for delete to authenticated using (private.owns_device(device_id, true));

create policy "transfers: read own" on public.transfers
  for select to authenticated using (user_id = (select auth.uid()));
create policy "transfers: create own" on public.transfers
  for insert to authenticated with check (
    user_id = (select auth.uid())
    and private.owns_device(from_device_id)
    and private.owns_device(to_device_id)
  );
create policy "transfers: update own" on public.transfers
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

create policy "relay_objects: read own" on public.relay_objects
  for select to authenticated using (user_id = (select auth.uid()));
create policy "relay_objects: register own" on public.relay_objects
  for insert to authenticated with check (
    user_id = (select auth.uid())
    -- Path must be {uid}/{transfer_id}/...
    and storage_path like (select auth.uid())::text || '/' || transfer_id::text || '/%'
    and exists (
      select 1 from public.transfers t
      where t.id = transfer_id and t.user_id = (select auth.uid())
    )
  );
create policy "relay_objects: delete own" on public.relay_objects
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "usage: read own" on public.usage_daily
  for select to authenticated using (user_id = (select auth.uid()));

