-- New auth user -> profile row.
create function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)), 80)
  )
  on conflict (id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function private.handle_new_user();

-- Devices: a revoked device stays revoked, and revoking drops its push
-- subscriptions so it stops receiving notifications immediately.
create function private.devices_before_update() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if old.revoked_at is not null then
    raise exception 'device is revoked' using errcode = '42501';
  end if;
  new.name := btrim(new.name);
  if new.revoked_at is not null then
    new.revoked_at := now();
    delete from public.push_subscriptions where device_id = new.id;
  end if;
  return new;
end $$;
create trigger devices_before_update before update on public.devices
  for each row execute function private.devices_before_update();

-- Serialize quota checks per user so two parallel requests can't both pass.
create function private.lock_user(p_user_id uuid) returns void
language sql as $$ select pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0)) $$;

create function private.bump_usage(p_user_id uuid, p_relay_bytes bigint, p_transfers int)
returns public.usage_daily
language plpgsql security definer set search_path = '' as $$
declare
  row public.usage_daily;
begin
  insert into public.usage_daily as u (user_id, day, relay_bytes, transfer_count)
  values (p_user_id, (now() at time zone 'utc')::date, p_relay_bytes, p_transfers)
  on conflict (user_id, day) do update
    set relay_bytes = u.relay_bytes + excluded.relay_bytes,
        transfer_count = u.transfer_count + excluded.transfer_count
  returning * into row;
  return row;
end $$;

-- Transfers insert: clients may only create fresh pending transfers, and only
-- so many per hour.
create function private.transfers_before_insert() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  recent int;
begin
  if new.file_count > private.limit_files_per_transfer() then
    raise exception 'too many files in one transfer' using errcode = 'PT413';
  end if;
  new.status := 'pending';
  new.relay_params := null;
  new.relay_started_at := null;
  new.delivered_at := null;
  new.created_at := now();
  new.expires_at := now() + interval '24 hours';

  perform private.lock_user(new.user_id);
  select count(*) into recent from public.transfers
    where user_id = new.user_id and created_at > now() - interval '1 hour';
  if recent >= private.limit_transfers_per_hour() then
    raise exception 'rate_limited: too many transfers this hour' using errcode = 'PT429';
  end if;

  perform private.bump_usage(new.user_id, 0, 1);
  return new;
end $$;
create trigger transfers_before_insert before insert on public.transfers
  for each row execute function private.transfers_before_insert();

-- Transfers update: enforce a small state machine and gate the relay.
create function private.transfers_before_update() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  -- current_user is the function owner inside SECURITY DEFINER, so look at
  -- the JWT role (Edge Functions with the service key) or the session user
  -- (pg_cron / psql run as postgres).
  is_service boolean := coalesce((select auth.role()) = 'service_role', false)
    or session_user in ('postgres', 'supabase_admin');
  recent int;
  missing int;
begin
  -- Starting a relay: allowed once, while pending, within limits.
  if new.relay_params is distinct from old.relay_params then
    if old.relay_params is not null or old.status <> 'pending' then
      raise exception 'relay parameters are immutable' using errcode = '42501';
    end if;
    if new.relay_params is null then
      raise exception 'relay parameters cannot be removed' using errcode = '42501';
    end if;
    if old.total_bytes > private.limit_relay_bytes_per_transfer() then
      raise exception 'too_large: transfer exceeds the relay size limit' using errcode = 'PT413';
    end if;
    perform private.lock_user(old.user_id);
    select count(*) into recent from public.transfers
      where user_id = old.user_id and relay_started_at > now() - interval '1 hour';
    if recent >= private.limit_relay_transfers_per_hour() then
      raise exception 'rate_limited: too many relayed transfers this hour' using errcode = 'PT429';
    end if;
    new.relay_started_at := now();
  end if;

  if new.status is distinct from old.status then
    if not is_service and not (
      (old.status = 'pending' and new.status in ('p2p', 'relayed', 'delivered', 'failed', 'cancelled'))
      or (old.status = 'p2p' and new.status in ('pending', 'delivered', 'failed', 'cancelled'))
      or (old.status = 'relayed' and new.status in ('delivered', 'failed', 'cancelled'))
    ) then
      raise exception 'invalid status change % -> %', old.status, new.status using errcode = '42501';
    end if;

    if new.status = 'relayed' then
      if new.relay_params is null then
        raise exception 'relay was never started' using errcode = '42501';
      end if;
      -- Every registered object must exist in storage and be no bigger than
      -- declared. This is what makes lying about byte_size pointless: such a
      -- transfer never becomes downloadable and is cleaned up.
      select count(*) into missing from public.relay_objects r
        where r.transfer_id = new.id
          and not exists (
            select 1 from storage.objects o
            where o.bucket_id = 'relay' and o.name = r.storage_path
              and coalesce((o.metadata ->> 'size')::bigint, 0) <= r.byte_size
          );
      if missing > 0 then
        raise exception 'relay upload incomplete or mismatched' using errcode = '42501';
      end if;
      if not exists (select 1 from public.relay_objects r where r.transfer_id = new.id and r.file_index = -1) then
        raise exception 'relay manifest missing' using errcode = '42501';
      end if;
    end if;

    if new.status = 'delivered' then
      new.delivered_at := now();
    end if;
  end if;

  return new;
end $$;
create trigger transfers_before_update before update on public.transfers
  for each row execute function private.transfers_before_update();

-- Relay objects: only for a transfer whose relay has started, still pending,
-- not expired; counted against per-transfer and per-day byte quotas.
create function private.relay_objects_before_insert() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  t public.transfers;
  used bigint;
  usage public.usage_daily;
begin
  if new.byte_size < 1 or new.byte_size > private.limit_relay_object_bytes() then
    raise exception 'too_large: relay object size out of range' using errcode = 'PT413';
  end if;

  select * into t from public.transfers where id = new.transfer_id;
  if t.relay_params is null or t.status <> 'pending' or t.expires_at < now() then
    raise exception 'transfer is not accepting relay uploads' using errcode = '42501';
  end if;

  perform private.lock_user(new.user_id);

  -- Allowance on top of total_bytes: 16-byte tag per 1 MiB chunk plus manifest.
  select coalesce(sum(byte_size), 0) into used from public.relay_objects where transfer_id = new.transfer_id;
  if used + new.byte_size > least(
       private.limit_relay_bytes_per_transfer(),
       t.total_bytes
     ) + private.limit_relay_object_bytes() + (t.total_bytes / (1024 * 1024) + t.file_count + 1) * 16 then
    raise exception 'too_large: relay upload exceeds the declared transfer size' using errcode = 'PT413';
  end if;

  usage := private.bump_usage(new.user_id, new.byte_size, 0);
  if usage.relay_bytes > private.limit_relay_bytes_per_day() then
    raise exception 'quota_exceeded: daily relay quota used up' using errcode = 'PT429';
  end if;

  new.created_at := now();
  return new;
end $$;
create trigger relay_objects_before_insert before insert on public.relay_objects
  for each row execute function private.relay_objects_before_insert();

-- ---------------------------------------------------------------------------
-- Storage: private bucket for encrypted relay chunks.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('relay', 'relay', false, 1024 * 1024 + 1024, array['application/octet-stream'])
on conflict (id) do update
  set public = false, file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Objects live at {uid}/{transfer_id}/{file_index}/{chunk_index} (or
-- {uid}/{transfer_id}/manifest). Users can only touch their own folder, and
-- can only upload an object that was first registered (and quota-checked) in
-- relay_objects. No UPDATE policy: objects can't be overwritten.
create policy "relay: read own folder" on storage.objects
  for select to authenticated
  using (bucket_id = 'relay' and (storage.foldername(name))[1] = (select auth.uid())::text);

create policy "relay: upload registered objects" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'relay'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and exists (
      select 1 from public.relay_objects r
      join public.transfers t on t.id = r.transfer_id
      where r.storage_path = objects.name
        and r.user_id = (select auth.uid())
        and t.status = 'pending'
    )
  );

create policy "relay: delete own folder" on storage.objects
  for delete to authenticated
  using (bucket_id = 'relay' and (storage.foldername(name))[1] = (select auth.uid())::text);

