-- DropLink core schema: tables, constraints, RLS, quotas.
--
-- Security model in one paragraph: every row belongs to exactly one auth user,
-- either directly (user_id) or through a device the user owns. RLS policies
-- only ever compare against auth.uid(). Clients get column-level UPDATE grants
-- so they can't rewrite ownership or quota-relevant columns, and every write
-- that matters for abuse (creating transfers, registering relay objects) goes
-- through triggers that enforce limits server side.

-- Internal helpers live in a schema that PostgREST doesn't expose.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create type public.device_kind as enum ('android', 'mac', 'windows', 'linux', 'ios', 'other');
create type public.transfer_status as enum (
  'pending', 'p2p', 'relayed', 'delivered', 'failed', 'cancelled', 'expired'
);

-- ---------------------------------------------------------------------------
-- Limits. Keep in sync with src/lib/config.ts (the client checks them for UX,
-- these are the ones that actually count).
-- ---------------------------------------------------------------------------
create function private.limit_relay_bytes_per_transfer() returns bigint
  language sql immutable as $$ select 100::bigint * 1024 * 1024 $$;
create function private.limit_relay_bytes_per_day() returns bigint
  language sql immutable as $$ select 500::bigint * 1024 * 1024 $$;
create function private.limit_relay_transfers_per_hour() returns int
  language sql immutable as $$ select 20 $$;
-- Cap on all transfer rows (P2P included) so nobody can spam the table.
create function private.limit_transfers_per_hour() returns int
  language sql immutable as $$ select 200 $$;
-- Relay objects are 1 MiB plaintext chunks + 16-byte GCM tag; the manifest is
-- capped to the same size. Matches the bucket's file_size_limit.
create function private.limit_relay_object_bytes() returns int
  language sql immutable as $$ select 1024 * 1024 + 1024 $$;
create function private.limit_files_per_transfer() returns int
  language sql immutable as $$ select 500 $$;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text check (char_length(display_name) <= 80),
  created_at timestamptz not null default now()
);

create table public.devices (
  -- Generated by the client so it can be stored next to the private key
  -- before the row exists.
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  kind public.device_kind not null default 'other',
  -- ECDH P-256 public key as a JWK. Reject anything that looks like a private
  -- key ("d") or isn't the expected curve.
  public_key jsonb not null check (
    jsonb_typeof(public_key) = 'object'
    and pg_column_size(public_key) < 1024
    and public_key ->> 'kty' = 'EC'
    and public_key ->> 'crv' = 'P-256'
    and public_key ? 'x'
    and public_key ? 'y'
    and not public_key ? 'd'
  ),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz
);
create index devices_user_id_idx on public.devices (user_id);

create table public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  device_id uuid not null references public.devices (id) on delete cascade,
  endpoint text not null unique check (endpoint ~ '^https://' and char_length(endpoint) <= 1024),
  p256dh text not null check (char_length(p256dh) <= 256),
  auth text not null check (char_length(auth) <= 64),
  created_at timestamptz not null default now()
);
create index push_subscriptions_device_id_idx on public.push_subscriptions (device_id);

create table public.transfers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  from_device_id uuid not null references public.devices (id) on delete cascade,
  to_device_id uuid not null references public.devices (id) on delete cascade,
  status public.transfer_status not null default 'pending',
  file_count int not null check (file_count >= 1),
  total_bytes bigint not null check (total_bytes >= 0 and total_bytes <= 1099511627776),
  -- Relay only: { v, epk (ephemeral ECDH public JWK), salt, ivPrefix }.
  -- No file names here; those live in the encrypted manifest object.
  relay_params jsonb check (relay_params is null or pg_column_size(relay_params) < 2048),
  relay_started_at timestamptz,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  expires_at timestamptz not null default now() + interval '24 hours',
  check (from_device_id <> to_device_id)
);
create index transfers_user_created_idx on public.transfers (user_id, created_at desc);
create index transfers_to_device_status_idx on public.transfers (to_device_id, status);
create index transfers_expires_idx on public.transfers (expires_at) where status in ('pending', 'relayed');

create table public.relay_objects (
  transfer_id uuid not null references public.transfers (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  storage_path text not null unique,
  -- -1 is the encrypted manifest, 0..n-1 are files.
  file_index int not null check (file_index >= -1),
  chunk_index int not null check (chunk_index >= 0),
  byte_size int not null,
  created_at timestamptz not null default now(),
  primary key (transfer_id, storage_path)
);
create index relay_objects_user_idx on public.relay_objects (user_id);

create table public.usage_daily (
  user_id uuid not null references auth.users (id) on delete cascade,
  day date not null default (now() at time zone 'utc')::date,
  relay_bytes bigint not null default 0,
  transfer_count int not null default 0,
  primary key (user_id, day)
);

-- ---------------------------------------------------------------------------
-- Privileges. Supabase grants everything to anon/authenticated by default;
-- tighten to exactly what the client needs. RLS still applies on top.
-- ---------------------------------------------------------------------------
revoke all on public.profiles, public.devices, public.push_subscriptions, public.transfers,
  public.relay_objects, public.usage_daily from anon, authenticated;

grant select on public.profiles to authenticated;
grant update (display_name) on public.profiles to authenticated;

grant select, insert on public.devices to authenticated;
grant update (name, last_seen_at, revoked_at) on public.devices to authenticated;

grant select, insert, delete on public.push_subscriptions to authenticated;

grant select, insert on public.transfers to authenticated;
grant update (status, delivered_at, relay_params) on public.transfers to authenticated;

grant select, insert, delete on public.relay_objects to authenticated;

grant select on public.usage_daily to authenticated;

